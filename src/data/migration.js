export function populationAt(ka) {
  const p = POPULATION;
  if (ka >= p[0][0]) return p[0][1];
  for (let i = 0; i + 1 < p.length; i++) {
    if (ka <= p[i][0] && ka >= p[i + 1][0]) {
      const f = (p[i][0] - ka) / (p[i][0] - p[i + 1][0] || 1);
      // interpolate in log space
      return Math.exp(Math.log(p[i][1]) + (Math.log(p[i + 1][1]) - Math.log(p[i][1])) * f);
    }
  }
  return p[p.length - 1][1];
}

export function formatPopulation(n) {
  if (n >= 1e8) return (n / 1e8).toFixed(n >= 1e9 ? 1 : 2).replace(/\.?0+$/, '') + ' 亿';
  if (n >= 1e4) return Math.round(n / 1e4) + ' 万';
  return Math.round(n).toString();
}

