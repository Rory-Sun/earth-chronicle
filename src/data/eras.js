export function eraAt(yearsBP) {
  for (const e of ERAS) if (yearsBP <= e.start && yearsBP > e.end) return e;
  return yearsBP > ERAS[0].start ? ERAS[0] : ERAS[ERAS.length - 1];
}

/** Human-readable Chinese time label */
const trim = (str) => (str.includes('.') ? str.replace(/0+$/, '').replace(/\.$/, '') : str);
export function formatYears(yearsBP) {
  if (yearsBP >= 1e9) return trim((yearsBP / 1e8).toFixed(yearsBP >= 4e9 ? 1 : 2)) + ' 亿年前';
  if (yearsBP >= 1e6) return trim((yearsBP / 1e6).toFixed(yearsBP >= 100e6 ? 0 : yearsBP >= 10e6 ? 1 : 2)) + ' 百万年前';
  if (yearsBP >= 1e4) return trim((yearsBP / 1e4).toFixed(yearsBP >= 1e5 ? 0 : 1)) + ' 万年前';
  if (yearsBP > 2000) return Math.round(yearsBP / 100) * 100 + ' 年前';
  const year = 2025 - Math.round(yearsBP);
  if (year <= 0) return `公元前 ${1 - year} 年`;
  return `公元 ${year} 年`;
}
